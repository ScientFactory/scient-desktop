import * as NodeFS from "node:fs";
import * as NodePath from "node:path";
import * as NodeURL from "node:url";

const directory = NodeURL.fileURLToPath(
  new URL("../apps/server/src/scient/skills/", import.meta.url),
);
const names = [
  "word-docx",
  "excel-xlsx",
  "powerpoint-pptx",
  "pdf-files",
  "google-workspace",
  "document-review",
  "document-template",
];

const entries = names.map((directoryName) => {
  const root = NodePath.join(directory, "built-ins", directoryName);
  const files = Object.fromEntries(
    NodeFS.readdirSync(root, { recursive: true, withFileTypes: true })
      .filter((entry) => entry.isFile())
      .map((entry) =>
        NodePath.join(entry.parentPath, entry.name)
          .slice(root.length + 1)
          .replaceAll("\\", "/"),
      )
      .sort()
      .map((relativePath) => [
        relativePath,
        NodeFS.readFileSync(NodePath.join(root, relativePath), "utf8"),
      ]),
  );
  return { directoryName, defaultActive: true, files };
});

const target = NodePath.join(directory, "BuiltInDocumentLabSkillSources.ts");
const generated = `// Generated by scripts/sync-document-lab-skills.mjs from built-ins/.
import type { BuiltInSkillSource } from "./BuiltInSkillSources.ts";

export const BUILT_IN_DOCUMENT_LAB_SKILL_SOURCES: ReadonlyArray<BuiltInSkillSource> =
  Object.freeze(${JSON.stringify(entries, null, 2)});
`;

NodeFS.writeFileSync(target, generated);
