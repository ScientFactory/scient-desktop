// Server bytecode for a target the packaging host cannot run (release Windows packages build on
// Linux): `generate` on the target OS from this build's staged app, `install` from the afterPack
// hook only for the same engine and module bytes, `check` that the shipped backend accepts it.
// Usage: generate <app-dir> <executable> <output-dir> | check <app-dir> <executable>
import * as NodeAssert from "node:assert/strict";
import * as NodeChildProcess from "node:child_process";
import * as NodeCrypto from "node:crypto";
import * as NodeFS from "node:fs";
import * as NodeModule from "node:module";
import * as NodePath from "node:path";
import * as NodeURL from "node:url";

const CACHE_DIRECTORY = "server-compile-cache";
const RECEIPT = "receipt.json";
// electron-builder's Arch enum order, as afterPack receives it.
const ELECTRON_BUILDER_ARCHES = ["ia32", "x64", "armv7l", "arm64", "universal"];
const CACHE_FILE = /^[a-f0-9]{8}$/;
const SERVER_MODULE = /^(app|server)\.asar\/apps\/server\/dist\/[^/\\]+\.mjs$/;

const readJson = (file) => JSON.parse(NodeFS.readFileSync(file, "utf8"));

// The packaged engine runs as Node without the build host's Node or Scient settings.
function engineEnvironment(extra) {
  const env = { ...process.env, ...extra, ELECTRON_RUN_AS_NODE: "1" };
  for (const name of Object.keys(env)) {
    if ((name.startsWith("NODE_") && !(name in extra)) || name.startsWith("T3CODE_")) {
      delete env[name];
    }
  }
  return env;
}

function readManifest(cacheDirectory) {
  const manifest = readJson(NodePath.join(cacheDirectory, "manifest.json"));
  NodeAssert.equal(manifest.format, 1, "Unsupported server bytecode manifest format");
  NodeAssert.equal(typeof manifest.runtime, "string", "Server bytecode manifest has no runtime");
  NodeAssert.ok(
    Array.isArray(manifest.entries) && manifest.entries.length > 0,
    "Server bytecode manifest has no entries",
  );
  for (const entry of manifest.entries) {
    NodeAssert.match(entry?.module ?? "", SERVER_MODULE, "Unexpected server bytecode module");
    NodeAssert.match(entry?.file ?? "", CACHE_FILE, "Unexpected server bytecode file name");
  }
  return manifest;
}

/** Generates bytecode with the staged app's own engine and records the module bytes it covers. */
export async function generateNativeServerCompileCache({ appDir, executable, output }) {
  const resources = NodePath.join(appDir, "resources");
  const prepared = NodePath.join(resources, CACHE_DIRECTORY);
  NodeAssert.ok(!NodeFS.existsSync(prepared), `${prepared} already exists`);
  NodeAssert.ok(!NodeFS.existsSync(output), `${output} already exists`);
  // The packaging hook itself generates, so this path stays the native packaging path.
  const prepare = NodeModule.createRequire(import.meta.url)("./prepare-server-compile-cache.cjs");
  const { platform, arch } = process;
  await prepare({
    appOutDir: appDir,
    electronPlatformName: platform,
    arch: ELECTRON_BUILDER_ARCHES.indexOf(arch),
    packager: {
      appInfo: { productFilename: NodePath.basename(executable, ".exe") },
      executableName: executable,
    },
  });
  const manifest = readManifest(prepared);
  // Node cannot read ASAR archives; the packaged engine hashes the modules as it loaded them.
  const digest = NodeChildProcess.spawnSync(
    NodePath.join(appDir, executable),
    [
      "-e",
      `const fs=require("node:fs"),crypto=require("node:crypto"),path=require("node:path");process.stdout.write(JSON.stringify(Object.fromEntries(${JSON.stringify(manifest.entries.map((entry) => entry.module))}.map(m=>[m,crypto.createHash("sha256").update(fs.readFileSync(path.join(${JSON.stringify(resources)},m))).digest("hex")]))))`,
    ],
    { env: engineEnvironment({}), encoding: "utf8", timeout: 60_000 },
  );
  NodeAssert.equal(
    digest.status,
    0,
    `Hashing server modules failed: ${digest.error ?? digest.stderr}`,
  );
  NodeFS.mkdirSync(NodePath.join(output, CACHE_DIRECTORY), { recursive: true });
  for (const file of ["manifest.json", ...manifest.entries.map((entry) => entry.file)]) {
    NodeFS.copyFileSync(
      NodePath.join(prepared, file),
      NodePath.join(output, CACHE_DIRECTORY, file),
    );
  }
  const receipt = {
    schemaVersion: 1,
    platform,
    arch,
    runtime: manifest.runtime,
    modules: JSON.parse(digest.stdout),
  };
  NodeFS.writeFileSync(NodePath.join(output, RECEIPT), `${JSON.stringify(receipt, null, 2)}\n`);
  return receipt;
}

/** Admits natively generated bytecode into a cross-built app, or fails the build. */
export async function installNativeServerCompileCache({
  appOutDir,
  platform,
  arch,
  electronVersion,
  source,
}) {
  const resources = NodePath.join(appOutDir, "resources");
  const target = NodePath.join(resources, CACHE_DIRECTORY);
  const receipt = readJson(NodePath.join(source, RECEIPT));
  const manifest = readManifest(NodePath.join(source, CACHE_DIRECTORY));
  NodeAssert.equal(receipt.schemaVersion, 1, "Unsupported server bytecode receipt");
  NodeAssert.equal(
    receipt.platform,
    platform,
    "Server bytecode was generated for another platform",
  );
  NodeAssert.equal(receipt.arch, arch, "Server bytecode was generated for another architecture");
  NodeAssert.equal(
    receipt.runtime,
    manifest.runtime,
    "Server bytecode receipt and manifest differ",
  );
  NodeAssert.ok(
    manifest.runtime.startsWith(`${electronVersion}-v`) &&
      manifest.runtime.includes(`-${platform}-${arch}-`),
    `Server bytecode runtime ${manifest.runtime} is not Electron ${electronVersion} on ${platform}/${arch}`,
  );
  NodeAssert.deepEqual(
    Object.keys(receipt.modules).sort(),
    manifest.entries.map((entry) => entry.module).sort(),
    "Server bytecode receipt and manifest cover different modules",
  );
  // Loaded here only: the Windows host runs generate and check without installed dependencies.
  const { extractFile } = await import("@electron/asar");
  for (const entry of manifest.entries) {
    const [archive, ...inner] = entry.module.split("/");
    const bytes = extractFile(NodePath.join(resources, archive), inner.join("/"));
    const actual = NodeCrypto.createHash("sha256").update(bytes).digest("hex");
    NodeAssert.equal(
      actual,
      receipt.modules[entry.module],
      `Server bytecode was generated for different ${entry.module} bytes`,
    );
  }
  NodeAssert.ok(!NodeFS.existsSync(target), `${target} already exists`);
  NodeFS.mkdirSync(target);
  for (const file of ["manifest.json", ...manifest.entries.map((entry) => entry.file)]) {
    NodeFS.copyFileSync(NodePath.join(source, CACHE_DIRECTORY, file), NodePath.join(target, file));
  }
  console.log(
    `[server-compile-cache] Installed server bytecode generated natively on ${platform}/${arch} (${String(manifest.entries.length)} modules)`,
  );
}

/** Loads every prepared module through the shipped backend preload and requires each to be accepted. */
export function checkServerCompileCache({ appDir, executable }) {
  const resources = NodePath.join(appDir, "resources");
  const manifest = readManifest(NodePath.join(resources, CACHE_DIRECTORY));
  const archive = manifest.entries[0].module.split("/")[0];
  const preload = NodePath.join(resources, "app.asar/apps/desktop/dist-electron/compileCache.cjs");
  // The preload reads its archive from the entry argument, which never runs: the probe exits first.
  const entry = NodePath.join(resources, archive, "apps/server/dist/bin.mjs");
  // Windows links prepared files into the cache, which needs the same volume as the app.
  const state = NodeFS.mkdtempSync(
    NodePath.join(NodePath.dirname(NodePath.resolve(appDir)), "scient-cache-check-"),
  );
  try {
    const probe = NodePath.join(state, "probe.mjs");
    NodeFS.writeFileSync(
      probe,
      `${manifest.entries.map((item) => `await import(${JSON.stringify(NodeURL.pathToFileURL(NodePath.join(resources, item.module)).href)});`).join("\n")}\nprocess.exit(0);\n`,
    );
    const result = NodeChildProcess.spawnSync(
      NodePath.join(appDir, executable),
      ["--require", preload, "--import", NodeURL.pathToFileURL(probe).href, entry],
      {
        env: engineEnvironment({
          NODE_DEBUG_NATIVE: "COMPILE_CACHE",
          TEMP: state,
          TMP: state,
          TMPDIR: state,
          XDG_CACHE_HOME: state,
        }),
        encoding: "utf8",
        timeout: 120_000,
      },
    );
    NodeAssert.equal(
      result.status,
      0,
      `Server bytecode check failed: ${result.error ?? result.stderr}`,
    );
    const accepted = manifest.entries.filter((item) =>
      result.stderr.includes(`${NodePath.basename(item.module)} was accepted`),
    );
    const missing = manifest.entries.filter((item) => !accepted.includes(item));
    NodeAssert.equal(
      missing.length,
      0,
      `The packaged engine did not accept prepared bytecode for ${missing.map((item) => item.module).join(", ")}:\n${result.stderr}`,
    );
    console.log(
      `[server-compile-cache] The packaged engine accepted prepared bytecode for all ${String(accepted.length)} modules`,
    );
  } finally {
    NodeFS.rmSync(state, { recursive: true, force: true });
  }
}

if (import.meta.main) {
  const [command, appDir, executable, output] = process.argv.slice(2);
  NodeAssert.ok(
    appDir && executable,
    "Usage: generate <app-dir> <executable> <output-dir> | check <app-dir> <executable>",
  );
  if (command === "generate") {
    NodeAssert.ok(output, "generate needs an output directory");
    const receipt = await generateNativeServerCompileCache({ appDir, executable, output });
    console.log(
      `[server-compile-cache] Generated ${receipt.platform}/${receipt.arch} server bytecode for ${String(Object.keys(receipt.modules).length)} modules (${receipt.runtime})`,
    );
  } else if (command === "check") {
    checkServerCompileCache({ appDir, executable });
  } else {
    throw new Error(`Unknown command ${String(command)}`);
  }
}
