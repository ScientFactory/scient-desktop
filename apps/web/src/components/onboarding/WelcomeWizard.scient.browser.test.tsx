import { WelcomeWizard } from "./WelcomeWizard";

function setup() {
  using stack = new DisposableStack();
  vi.clearAllMocks();
  stack.use(
    stubGlobal(
      "ResizeObserver",
      class {
        observe() {}
        unobserve() {}
        disconnect() {}
      },
    ),
  );
  stack.use(vi.spyOn(Element.prototype, "getAnimations").mockReturnValue([]));
  mocks.projects = [{ id: "test-project", environmentId: "test-env", workspaceRoot: "/project" }];
  mocks.complete.mockReset().mockResolvedValue(undefined);
  mocks.refresh.mockReset().mockResolvedValue(undefined);
  mocks.importThreads
    .mockReset()
    .mockResolvedValue({ _tag: "Success", value: { importedCount: 28, skippedCount: 1 } });
  return stack.move();
}

async function click(label: string) {
  const button = [...document.querySelectorAll("button")].find(
    (element) => element.textContent?.trim() === label,
  );
  expect(button, `button ${label}`).toBeDefined();
  await act(async () => button!.click());
}

// regression: 352cbecb13 fix(privacy): withhold unapproved policy links
it("withholds the privacy link and disclosure while continuing to agent setup", async () => {
  const onDone = vi.fn();
  using _setup = setup();
  await using _screen = await render(<WelcomeWizard localAvailable onDone={onDone} />);
  expect(document.querySelector("h1")?.textContent?.trim()).toBe("Connect your computers");
  expect(document.querySelectorAll("a")).toHaveLength(0);
  expect(document.body.textContent).not.toMatch(/privacy policy|data collection|opt[ -]in/i);

  await click("Continue");
  expect(document.querySelector("h1")?.textContent?.trim()).toBe("Connect your agents");
  expect(onDone).not.toHaveBeenCalled();
});
